def _count(text: str, ch: str) -> int:
    return text.count(ch)


def audit(text: str) -> dict:
    """客觀驗證一段 cheer 文字係咪廣東話口語(唔係普通話書面語)。

    回傳 dict:
      ok            — 全部通過
      en_leaks      — 違例英文字 token
      mandarin_hits — 書面普通話詞 / 比例失衡
      ratios        — 嘅/的、咗/了、係/是、喺/在 比例
      density       — 廣東話助詞 per 100 字
      issues        — 人話解釋(直接塞返落 retry prompt)
    """
    t = text or ""
    zh_len = len(re.findall(r"[\u3400-\u9fff]", t))
    res: dict = {"ok": False, "en_leaks": [], "mandarin_hits": [], "ratios": {},
                 "density": 0.0, "issues": []}

    # ── 英文字 token ──
    for tok in re.findall(r"[A-Za-z][A-Za-z0-9_\-\.]*", t):
        if tok not in ALLOWED_EN:
            res["en_leaks"].append(tok)
    res["en_leaks"] = sorted(set(res["en_leaks"]))

    # ── 書面普通話詞 ──
    for ph in MANDARIN_PHRASES:
        n = t.count(ph)
        if n:
            res["mandarin_hits"].append(f"{ph}×{n}")
    # 簡體字(廣東話用繁體,出現簡體 = 出錯)
    # v3.3.67b:移除「台」—— 「平台」「台燈」喺繁體中文一樣用得,原本會誤判成簡體字令 audit 假失敗
    simp = re.findall(r"[们这说时会国东车马长门问间无点动产权变与发]", t)
    if simp:
        res["mandarin_hits"].append(f"簡體字×{len(simp)}:「{''.join(sorted(set(simp)))}」")

    # ── 口語比例 ──
    def ratio(mandarin_ch: str, canto_ch: str) -> tuple:
        m = _count(t, mandarin_ch)
        c = _count(t, canto_ch)
        tot = m + c
        return (c / tot if tot else 1.0), m, c

    r_de, n_de, n_ge = ratio("的", "嘅")
    r_le, n_le, n_lo = ratio("了", "咗")
    r_shi, n_shi, n_si = ratio("是", "係")
    r_zai, n_zai, n_zo = ratio("在", "喺")
    res["ratios"] = {
        "ge_of_de": round(r_de, 2), "de": n_de, "ge": n_ge,
        "lo_of_le": round(r_le, 2), "le": n_le, "lo": n_lo,
        "si_of_shi": round(r_shi, 2), "shi": n_shi, "si": n_si,
        "zo_of_zai": round(r_zai, 2), "zai": n_zai, "zo": n_zo,
    }
    res["density"] = round(sum(1 for ch in t if ch in CANTONESE_PARTICLES) / (zh_len / 100.0), 1) if zh_len else 0.0

    # ── 判定 ──
    issues: list[str] = []
    if res["en_leaks"]:
        issues.append("有英文字漏咗:" + ", ".join(res["en_leaks"][:8]))
    if res["mandarin_hits"]:
        issues.append("有普通話書面語:" + ", ".join(res["mandarin_hits"][:8]))
    # 比例門檻(只喺對方字數夠多先判,免得短句誤報)
    if n_de >= 4 and r_de < 0.55:
        issues.append(f"用咗 {n_de} 個「的」但只有 {n_ge} 個「嘅」→ 書面普通話(粵語要用「嘅」)")
    if n_le >= 4 and r_le < 0.50:
        issues.append(f"用咗 {n_le} 個「了」但只有 {n_lo} 個「咗」→ 書面普通話(粵語用「咗」)")
    if n_shi >= 3 and r_shi < 0.60:
        issues.append(f"用咗 {n_shi} 個「是」但只有 {n_si} 個「係」→ 書面普通話(粵語用「係」)")
    if n_zai >= 4 and r_zai < 0.40:
        issues.append(f"用咗 {n_zai} 個「在」但只有 {n_zo} 個「喺」→ 書面普通話(粵語用「喺」)")
    if zh_len >= 120 and res["density"] < 4.0:
        issues.append(f"粵語助詞密度只有 {res['density']} 個 per 100 字(要 ≥4)→ 唔夠口語")
    res["issues"] = issues
    res["ok"] = not issues
    return res


def rewrite(text: str) -> str:
    """決定式把普通話書面詞換成廣東話(validator 之後嘅最後防線)。"""
    t = text or ""
    # 長詞優先
    for src in sorted(MANDARIN_TO_CANTONESE, key=len, reverse=True):
        dst = MANDARIN_TO_CANTONESE[src]
        if src in t:
            t = t.replace(src, dst)
    # 清理重複用詞(替换後可能出現「嘅嘅」)
    t = re.sub(r"(嘅){2,}", "嘅", t)
    t = re.sub(r"(咗){2,}", "咗", t)
    t = re.sub(r"(係){2,}", "係", t)
    # ── v3.3.68 (2026-10-30)第四層:剝走結構旁白 ──
    # 2026-10-30 10:07 出嘅稿寫咗「第二段講返你嘅身體狀態,」「今朝第一句
    # 就想同你講」——模型喺度自爆稿嘅結構,TTS 讀出嚟好核突。
    t = re.sub(r"第[一二三四五六七八九十]+段(?:講返)?[^，。\n]{0,14}[，,]\s*", "", t)
    t = re.sub(r"第[一二三四五六七八九十]+句", "", t)
