def tidy_numbers(text: str) -> str:
    """語音用嘅數字整理(只影響 voice,唔影響 app 顯示)。

    - 0.33847734 → 0.34(讀出嚟唔會一個個數字唸)
    - 61.0% → 61%(唔好讀「百分之六十一点零」)
    - 12.8509 → 12.9
    - 「10 月 27 日」→「十月二十七號」(日期唔用阿拉伯數字)
    - 「2026-10-28」→「二零二六年十月二十八號」
    """
    t = text or ""
    t = re.sub(r"\b(\d+)\.(\d{3,})\b",
                lambda m: f"{round(float(m.group(0)), 2):g}", t)
    t = re.sub(r"(\d+)\.0+%", r"\1%", t)
    def _cn_digit(n: int) -> str:
        return "零一二三四五六七八九"[n] if 0 <= n <= 9 else str(n)

    def _cn_year(y: str) -> str:
        return "".join(_cn_digit(int(ch)) for ch in y)

    def _iso(m):
        y, mo, d = m.group(1), int(m.group(2)), int(m.group(3))
        return f"{_cn_year(y)}年{_CN_MONTH[mo - 1]}月{_CN_DAY[d - 1]}號"
    t = re.sub(r"(\d{4})-(\d{2})-(\d{2})", _iso, t)
    def _md(m):
        mo, d = int(m.group(1)), int(m.group(2))
        return f"{_CN_MONTH[mo - 1]}月{_CN_DAY[d - 1]}號"
    t = re.sub(r"(\d{1,2})\s*月\s*(\d{1,2})\s*[日號]", _md, t)
    return t


