def _strip_english_tokens(t: str) -> str:
    """剝走所有唔喺 ALLOWED_EN 入面嘅英文字 token(決定式,唔會漏網)。

    v3.3.67b (2026-10-30) 修正:之前剝走英文會留低「孤兒」殘渣 ——
    「多啲深色蔬菜、Omega 3 食物」剝走 "Omega" 後變成「、 3 食物」,
    讀出嚟變成「逗三食物」。三個修法:
      1. 先用「英文片語 → 中文」對照表處理已知術語(Omega-3 → 奧米加三)
      2. 剝走嘅未知 token 用 marker 標記,連同後面嘅孤兒數字一齊清走
      3. 清走空懸嘅標點 / 空格(「、 食物」→「、食物」)
    """
    if not t:
        return t

    # (1) 已知片語(必須喺 token 剝除之前做,唔然 "Omega" 會被拆走)
    for pat, rep in _EN_PHRASE_ZH:
        t = re.sub(pat, rep, t, flags=re.IGNORECASE)

    def _repl(m: re.Match) -> str:
        tok = m.group(0)
        if tok in ALLOWED_EN:
            return tok
        low = tok.lower()
        if low in _EN_BRAND_ZH:
            return _EN_BRAND_ZH[low]
        # 夾喺中文字之間(例:「用Hugging Face入侵」)→ 標記,之後連孤兒數字清走
        return "\x00"

    t = re.sub(r"[A-Za-z][A-Za-z0-9_\-\.]*['\u2019]?", _repl, t)
    # (2) 清走 marker,同埋「跟住被剝走嘅英文 token」嘅孤兒數字。
    # ⚠️ v3.3.67d:唔可以無腦食數字 —— 「McDonald's 3 個」會變「食咗 個」
    # (合法數量被誤刪)。只有喺「數字後面冇量詞/單位」時先當孤兒清走;
    # 有量詞(個/隻/件/次…)就當合法數量,保留。
    def _orphan_num(m: re.Match) -> str:
        tail = t[m.end():].lstrip()
        nxt = tail[:1]
        if nxt and (nxt in _MEASURE_CHARS or nxt in _UNIT_CHARS):
            return " " + m.group(1)          # 合法數量 → 保留
        return ""                            # 孤兒數字 → 清走

    t = re.sub(r"\x00[ \t]*(\d+(?:\.\d+)?)", _orphan_num, t)
    t = t.replace("\x00", "")
    # (3) 清走殘留:多餘空格 / 標點前空格 / 中文之間空格 / 空懸標點
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r"[ \t]+([，。、！？：；）】」])", r"\1", t)
    t = re.sub(r"([（【「])[ \t]+", r"\1", t)
    t = re.sub(r"([一-鿿])[ \t]+([一-鿿])", r"\1\2", t)
    t = re.sub(r"([、，,])[ \t]+", r"\1", t)
    # 剝走英文後剩低嘅孤兒撇號(例:"McDonald's" → "McDonald" + "'s" → "'")
    t = re.sub(r"['\u2019]", "", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


